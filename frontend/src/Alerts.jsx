import { useEffect, useState } from "react";

function Alerts() {
  const [alerts, setAlerts] = useState([]);
  const [loading, setLoading] = useState(true);

  const fetchAlerts = () => {
    setLoading(true);

    fetch("http://127.0.0.1:8000/alerts/")
      .then((response) => response.json())
      .then((data) => {
        setAlerts(data);
        setLoading(false);
      })
      .catch((error) => {
        console.error("Error fetching alerts:", error);
        setLoading(false);
      });
  };

  useEffect(() => {
    fetchAlerts();
  }, []);

  const openAlerts = alerts.filter(
    (alert) => alert.status === "Open"
  ).length;

  const highRiskAlerts = alerts.filter(
    (alert) =>
      alert.risk_level === "High" ||
      alert.risk_level === "Critical"
  ).length;

  const criticalAlerts = alerts.filter(
    (alert) => alert.risk_level === "Critical"
  ).length;

  return (
    <div>
      {/* Header */}
      <div className="header">
        <div>
          <h1>Security Alerts</h1>
          <p>Monitor security events and suspicious activities</p>
        </div>

        <button
          onClick={fetchAlerts}
          style={{
            padding: "10px 18px",
            border: "none",
            borderRadius: "8px",
            background: "#2563eb",
            color: "white",
            cursor: "pointer",
            fontSize: "14px"
          }}
        >
          🔄 IBM
        </button>
      </div>

      {/* Alert Summary Cards */}
      <section className="cards">

        <div className="card">
          <p>Total Alerts</p>
          <h2>{alerts.length}</h2>
          <span>All security alerts</span>
        </div>

        <div className="card">
          <p>Open Alerts</p>
          <h2>{openAlerts}</h2>
          <span>Requires attention</span>
        </div>

        <div className="card">
          <p>High Risk</p>
          <h2>{highRiskAlerts}</h2>
          <span>High and critical alerts</span>
        </div>

        <div className="card">
          <p>Critical</p>
          <h2>{criticalAlerts}</h2>
          <span>Immediate attention</span>
        </div>

      </section>

      {/* Alerts Table */}
      <section className="panel">

        <div className="panel-header">
          <div>
            <h2>Security Alert Records</h2>
            <p>Detected security events from the monitoring system</p>
          </div>
        </div>

        {loading ? (

          <div className="empty">
            <h3>Loading alerts...</h3>
          </div>

        ) : alerts.length === 0 ? (

          <div className="empty">
            <div>🛡️</div>
            <h3>No security alerts</h3>
            <p>
              Alerts generated by the security system will appear here.
            </p>
          </div>

        ) : (

          <div
            style={{
              overflowX: "auto",
              marginTop: "20px"
            }}
          >

            <table
              style={{
                width: "100%",
                borderCollapse: "collapse"
              }}
            >

              <thead>
                <tr style={{ textAlign: "left" }}>
                  <th style={{ padding: "14px" }}>Alert ID</th>
                  <th style={{ padding: "14px" }}>User</th>
                  <th style={{ padding: "14px" }}>Device</th>
                  <th style={{ padding: "14px" }}>Alert Type</th>
                  <th style={{ padding: "14px" }}>Risk Score</th>
                  <th style={{ padding: "14px" }}>Risk Level</th>
                  <th style={{ padding: "14px" }}>Time</th>
                  <th style={{ padding: "14px" }}>Status</th>
                </tr>
              </thead>

              <tbody>

                {alerts.map((alert) => (

                  <tr key={alert.id}>

                    <td style={{ padding: "14px" }}>
                      🚨 {alert.alert_id}
                    </td>

                    <td style={{ padding: "14px" }}>
                      {alert.user_id}
                    </td>

                    <td style={{ padding: "14px" }}>
                      {alert.device_id}
                    </td>

                    <td style={{ padding: "14px" }}>
                      {alert.alert_type}
                    </td>

                    <td style={{ padding: "14px", fontWeight: "600" }}>
                      {alert.risk_score}
                    </td>

                    <td style={{ padding: "14px" }}>
                      <span
                        style={{
                          color:
                            alert.risk_level === "Critical"
                              ? "#dc2626"
                              : alert.risk_level === "High"
                              ? "#ea580c"
                              : alert.risk_level === "Medium"
                              ? "#d97706"
                              : "#16a34a",
                          fontWeight: "600"
                        }}
                      >
                        {alert.risk_level}
                      </span>
                    </td>

                    <td style={{ padding: "14px" }}>
                      {alert.timestamp}
                    </td>

                    <td style={{ padding: "14px" }}>
                      <span
                        style={{
                          color:
                            alert.status === "Open"
                              ? "#dc2626"
                              : "#16a34a",
                          fontWeight: "600"
                        }}
                      >
                        ● {alert.status}
                      </span>
                    </td>

                  </tr>

                ))}

              </tbody>

            </table>

          </div>

        )}

      </section>

    </div>
  );
}

export default Alerts;